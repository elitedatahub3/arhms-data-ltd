import { NextRequest, NextResponse } from 'next/server'
import { createServerClient } from '@/lib/supabase'
import { createRouteHandlerClient } from '@/lib/supabase-server'
import { cookies } from 'next/headers'
import { Ratelimit } from '@upstash/ratelimit'
import { Redis } from '@upstash/redis'
import { purchaseDataWithWallet } from '@/lib/wallet-data-purchase'
import { checkMtnRegistration, registrationRequiredBody } from '@/lib/mtn-registration-gate'

const purchaseRateLimit = new Ratelimit({
    redis: Redis.fromEnv(),
    limiter: Ratelimit.slidingWindow(3, '10 s'),
    prefix: 'rl:purchase',
})

export async function POST(request: NextRequest) {
    try {
        const cookieStore = await cookies()
        const supabaseUserClient = await createRouteHandlerClient()
        const { data: { user: authUser }, error: authError } = await supabaseUserClient.auth.getUser()

        if (authError || !authUser) {
            return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
        }

        const user = authUser
        const userId = user.id

        let rateLimitOk = true;
        try {
            const rlResult = await purchaseRateLimit.limit(userId)
            rateLimitOk = rlResult.success
        } catch (rlError) {
            console.error('[Purchase] Rate limit error, bypassing:', rlError)
        }
        
        if (!rateLimitOk) {
            return NextResponse.json({ error: 'Too many requests. Please wait.' }, { status: 429 })
        }

        let body: any;
        try {
            body = await request.json()
        } catch (e) {
            return NextResponse.json({ error: 'Invalid request body' }, { status: 400 })
        }

        // referenceCode is now generated by the frontend to act as an idempotency key.
        // If the same referenceCode is submitted twice, the second request will fail on
        // the unique constraint, preventing double orders.
        const { packageId, phoneNumber, referenceCode: clientReferenceCode } = body

        if (!phoneNumber || typeof phoneNumber !== 'string') {
            return NextResponse.json({ error: 'Phone number is required' }, { status: 400 })
        }

        const cleanPhone = phoneNumber.replace(/\s+/g, '')
        const ghanaPhoneRegex = /^(0\d{9}|233\d{9})$/

        if (!ghanaPhoneRegex.test(cleanPhone)) {
            return NextResponse.json({
                error: 'Invalid phone number format. Use Ghana format: 0XXXXXXXXX or 233XXXXXXXXX'
            }, { status: 400 })
        }

        // Service role client for privileged operations
        const supabase = createServerClient()

        // Everything from the idempotency check to supplier fulfilment lives in
        // lib/wallet-data-purchase.ts, shared with USSD member orders so both charge
        // and fulfil a bundle the same way.
        const result = await purchaseDataWithWallet({
            supabase,
            userId,
            packageId,
            phoneNumber,
            referenceCode: clientReferenceCode,
            // MTN registration gate. Runs before the wallet is touched, so a refusal
            // charges nothing and creates no order. Off unless an admin turns it on.
            beforeCharge: async (pkg) => {
                const gate = await checkMtnRegistration(supabase, phoneNumber, pkg.network, 'site')
                return gate.gated
                    ? { status: 409, body: registrationRequiredBody([gate.normalizedNumber]) }
                    : null
            },
        })

        if (!result.ok) {
            return NextResponse.json(result.body ?? { error: result.error }, { status: result.status })
        }

        if (result.isDuplicate) {
            // Order already exists — this is a duplicate request. Return success with existing data.
            return NextResponse.json({ success: true, isDuplicate: true, order: result.order })
        }

        // Return immediately — don't wait for fulfillment/emails/SMS
        return NextResponse.json({
            success: true,
            order: {
                id: result.order.id,
                reference_code: result.order.reference_code,
                status: 'pending',
                network: result.network,
                size: result.size,
                phone_number: phoneNumber,
                price: result.price,
                new_balance: result.newBalance,
            },
        })
    } catch (error: any) {
        console.error('Purchase error:', error)
        return NextResponse.json({ error: error.message ? `Internal server error: ${error.message}` : 'Internal server error' }, { status: 500 })
    }
}

async function updateCustomerPurchases(
    supabase: any,
    userId: string,
    phoneNumber: string,
    amount: number
) {
    const { data: existing } = await supabase
        .from('customer_purchases')
        .select('*')
        .eq('user_id', userId)
        .eq('customer_phone', phoneNumber)
        .single()

    if (existing) {
        await supabase
            .from('customer_purchases')
            .update({
                total_purchases: existing.total_purchases + 1,
                total_spent: existing.total_spent + amount,
                last_purchase_at: new Date().toISOString(),
            })
            .eq('id', existing.id)
    } else {
        await supabase.from('customer_purchases').insert({
            user_id: userId,
            customer_phone: phoneNumber,
            total_purchases: 1,
            total_spent: amount,
            first_purchase_at: new Date().toISOString(),
            last_purchase_at: new Date().toISOString(),
        })
    }
}
